import { test, expect } from "@playwright/test";
import fs from "node:fs/promises";
import path from "node:path";
import { createPost } from "../helpers/fixtures";
import { runCli, runCliOk } from "../helpers/cli";
import { E2E, runId } from "../helpers/env";

test("长 TTL：发布、关联替换、投递恢复、下线与重建更新真实页面", async ({ page, request }, info) => {
  test.setTimeout(180_000);
  const slug = `cache-${runId()}`;
  const oldTag = `${slug}-old`;
  const newTag = `${slug}-new`;
  const evidence: { step: string; pass: boolean }[] = [];
  expect((await request.get(`/p/${slug}`)).status()).toBe(404);
  const publish = async (title: string, tag: string, extra?: NodeJS.ProcessEnv) => {
    const dir = await createPost({ slug, title, tags: [tag], body: `${title} 完整正文`, publishedAt: "2026-08-05" });
    return runCli(["publish", dir], extra);
  };
  expect((await publish("CACHE_REV_ONE", oldTag)).code).toBe(0);
  await page.goto("/");
  await page.getByRole("link", { name: "CACHE_REV_ONE", exact: true }).click();
  await expect(page.getByText("CACHE_REV_ONE 完整正文", { exact: true })).toBeVisible();
  evidence.push({ step: "negative cache and anonymous navigation", pass: true });
  await page.goto(`/tags/${oldTag}`);
  await expect(page.getByRole("link", { name: "CACHE_REV_ONE", exact: true })).toBeVisible();
  expect((await publish("CACHE_REV_TWO", newTag)).code).toBe(0);
  await page.goto(`/tags/${oldTag}`);
  await expect(page.getByRole("link", { name: "CACHE_REV_ONE", exact: true })).toHaveCount(0);
  await page.goto(`/tags/${newTag}`);
  await expect(page.getByRole("link", { name: "CACHE_REV_TWO", exact: true })).toBeVisible();
  evidence.push({ step: "old and new associations", pass: true });
  const pending = await publish("CACHE_REV_THREE", newTag, { CACHE_REVALIDATE_URL: "http://127.0.0.1:1/api/revalidate" });
  expect(pending.stdout).toContain("pending");
  await runCliOk(["cache", "retry"]);
  await page.goto("/");
  await expect(page.getByRole("link", { name: "CACHE_REV_THREE", exact: true })).toBeVisible();
  evidence.push({ step: "durable retry", pass: true });
  await runCliOk(["unpublish", slug]);
  expect((await request.get(`/p/${slug}`)).status()).toBe(404);
  expect(await (await request.get("/sitemap.xml")).text()).not.toContain(`/p/${slug}`);
  await runCliOk(["content", "delete", slug]);
  expect((await publish("CACHE_REBUILT", newTag)).code).toBe(0);
  await page.goto(`/p/${slug}`);
  await expect(page.getByRole("heading", { name: "CACHE_REBUILT" })).toBeVisible();
  evidence.push({ step: "unpublish delete rebuild", pass: true });
  const report = { environment: "isolated loopback PG/FS, next start, TTL=86400", command: "pnpm e2e", evidence };
  const file = info.outputPath("acceptance.json");
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, JSON.stringify(report, null, 2));
  await info.attach("cache acceptance", { path: file, contentType: "application/json" });
});
